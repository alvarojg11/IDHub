/**
 * Antibacterial spectrum reference data.
 *
 * This tool separates expected in vitro activity from clinical preference.
 * Real decisions still require syndrome, source control, severity, patient factors,
 * susceptibility testing, local antibiograms, and institutional guidance.
 */

export type SpectrumActivity = "preferred" | "active" | "variable" | "inactive" | "avoid" | "site-only";

export type SpectrumCell = {
  activity: SpectrumActivity;
  note?: string;
  requiresSusceptibility?: boolean;
  siteCaveat?: string;
  resistanceCaveat?: string;
};

export type Antibiotic = {
  name: string;
  className: string;
  route: "IV" | "PO" | "IV/PO" | "PO/local";
  aliases: string[];
  note?: string;
};

