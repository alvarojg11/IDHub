export type OrganismCategory =
  | "Gram-positive cocci"
  | "Gram-positive rods"
  | "Enterobacterales"
  | "Non-fermenters"
  | "Respiratory / GN diplococci"
  | "GI / water / zoonotic"
  | "Anaerobes"
  | "Atypical / intracellular";

export type OrganismSpectrum = {
  organism: string;
  category: OrganismCategory;
  aliases: string[];
  summary: string;
  keyCaveats: string[];
  antibiotics: Partial<Record<AntibioticName, SpectrumCell>>;
};

const p = (note?: string): SpectrumCell => ({ activity: "preferred", note });
const a = (note?: string): SpectrumCell => ({ activity: "active", note });
const v = (note?: string): SpectrumCell => ({ activity: "variable", note, requiresSusceptibility: true });
const r = (note?: string): SpectrumCell => ({ activity: "inactive", note });
const avoid = (note: string): SpectrumCell => ({ activity: "avoid", note });
const site = (note: string): SpectrumCell => ({ activity: "site-only", note, siteCaveat: note });

